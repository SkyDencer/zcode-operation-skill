/**
 * Domain registry — manages per-domain metadata for hierarchical routing.
 *
 * Reads domain metadata from data/domains/<domain>/meta.json files.
 * Each meta.json has: name, description, keywords.
 *
 * On build-index, auto-populates domain metadata from the skill corpus:
 *   - Merges all skill descriptions per domain
 *   - Collects union of all skill keywords per domain
 *   - Counts total skills per domain
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync, readdirSync } from 'node:fs';
import { join, resolve } from 'node:path';

const DOMAINS_DIR = resolve('data/domains');

/**
 * @typedef {Object} DomainMeta
 * @property {string} name — domain identifier
 * @property {string} description — human-readable domain description
 * @property {string[]} keywords — domain-level keywords for fast matching
 * @property {number} skillCount — number of skills in this domain
 */

/**
 * Read a single domain's metadata.
 *
 * @param {string} domainName
 * @returns {DomainMeta|null}
 */
export function readDomainMeta(domainName) {
  const metaPath = join(DOMAINS_DIR, domainName, 'meta.json');
  if (!existsSync(metaPath)) return null;
  try {
    return JSON.parse(readFileSync(metaPath, 'utf-8'));
  } catch {
    return null;
  }
}

/**
 * Read all domain metadata from data/domains/.
 *
 * @returns {DomainMeta[]}
 */
export function readAllDomainMeta() {
  if (!existsSync(DOMAINS_DIR)) return [];
  const results = [];
  try {
    const entries = readFileSync(DOMAINS_DIR, 'utf-8')
      ? []
      : [];
    // readdirSync is used below instead
  } catch {}

  let dirs;
  try {
    dirs = readdirSync(DOMAINS_DIR, { withFileTypes: true });
  } catch {
    return [];
  }

  for (const entry of dirs) {
    if (!entry.isDirectory()) continue;
    const meta = readDomainMeta(entry.name);
    if (meta) results.push(meta);
  }
  return results;
}

/**
 * Create a domain metadata directory and meta.json file.
 *
 * @param {string} domainName
 * @param {string} description
 * @param {string[]} keywords
 */
export function createDomainMeta(domainName, description, keywords) {
  const dir = join(DOMAINS_DIR, domainName);
  mkdirSync(dir, { recursive: true });
  const meta = {
    name: domainName,
    description,
    keywords,
    skillCount: 0,
  };
  writeFileSync(join(dir, 'meta.json'), JSON.stringify(meta, null, 2), 'utf-8');
  return meta;
}

/**
 * Auto-populate or update domain metadata from a skill index.
 *
 * For each domain found in skills, merges existing metadata with corpus-derived
 * aggregates. If no meta.json exists, creates one.
 *
 * Description is generated by joining all skill descriptions for the domain
 * (capped at 500 chars) rather than using a generic placeholder, so that
 * matchDomainsToQuery has meaningful text to rank against queries.
 *
 * @param {Array<{name:string, description:string, keywords:string[], domains:string[]}>} skills
 */
export function populateDomainsFromSkills(skills) {
  const domainMap = new Map(); // domain → { descriptions, keywords, skills }

  for (const skill of skills) {
    const domains = skill.domains || [];
    for (const domain of domains) {
      if (!domainMap.has(domain)) {
        domainMap.set(domain, {
          descriptions: [],
          keywords: new Set(),
          skillCount: 0,
          skillNames: [],
        });
      }
      const agg = domainMap.get(domain);
      agg.descriptions.push(skill.description);
      for (const kw of skill.keywords || []) {
        agg.keywords.add(kw.toLowerCase());
      }
      agg.skillCount++;
      agg.skillNames.push(skill.name);
    }
  }

  for (const [domain, agg] of domainMap) {
    const metaPath = join(DOMAINS_DIR, domain, 'meta.json');
    let existing = null;
    if (existsSync(metaPath)) {
      try {
        existing = JSON.parse(readFileSync(metaPath, 'utf-8'));
      } catch {}
    }

    // Generate a meaningful description from aggregated skill descriptions
    // rather than using a placeholder like "Skills related to X domain".
    const aggregatedDesc = agg.descriptions.join('. ').slice(0, 500);
    const description =
      (existing && existing.description && !existing.description.includes('Skills related to'))
        ? existing.description
        : aggregatedDesc;

    const mergedKeywords = new Set([
      ...(existing?.keywords || []),
      ...[...agg.keywords].slice(0, 50),
    ]);

    const meta = {
      name: domain,
      description,
      keywords: [...mergedKeywords],
      skillCount: Math.max(existing?.skillCount ?? 0, agg.skillCount),
    };

    mkdirSync(join(DOMAINS_DIR, domain), { recursive: true });
    writeFileSync(metaPath, JSON.stringify(meta, null, 2), 'utf-8');
  }

  return domainMap;
}

/**
 * Build a compact domain index for fast keyword matching.
 *
 * Returns a map from domain name → { descriptionTokens, keywordTokens }.
 *
 * @param {string[]} queryTokens
 * @param {DomainMeta[]} domains
 * @returns {Map<string, { descriptionScore: number, keywordScore: number, totalScore: number }>}
 */
export function matchDomainsToQuery(queryTokens, domains) {
  const results = new Map();

  for (const domain of domains) {
    const descTokens = tokenize(domain.description);
    const kwTokens = domain.keywords.map((k) => tokenize(k)).flat();

    let descScore = 0;
    for (const qt of queryTokens) {
      if (descTokens.includes(qt)) descScore++;
    }
    descScore = descScore / Math.max(descTokens.length, 1);

    let kwScore = 0;
    for (const qt of queryTokens) {
      if (kwTokens.includes(qt)) kwScore++;
    }
    kwScore = kwScore / Math.max(kwTokens.length, 1);

    const totalScore = 0.4 * descScore + 0.6 * kwScore;

    results.set(domain.name, {
      descriptionScore: Math.round(descScore * 100) / 100,
      keywordScore: Math.round(kwScore * 100) / 100,
      totalScore: Math.round(totalScore * 100) / 100,
    });
  }

  return results;
}

/**
 * Lightweight tokenizer for domain matching (no external deps).
 */
function tokenize(text) {
  if (!text) return [];
  return text
    .toLowerCase()
    .replace(/[^a-z0-9\- _]/g, ' ')
    .split(/\s+/)
    .filter((t) => t.length > 1);
}
